import {
  writeText,
  formatDateHuman,
  sortByDeadline,
  filterByStatus,
  priorityEmoji,
  statusEmoji,
} from "./utils.js";

// ─────────────────────────────────────────
// Build a single task block in Markdown
// ─────────────────────────────────────────
function buildTaskBlock(task) {
  const checkbox = task.status === "completed" ? "[x]" : "[ ]";
  const lines = [
    `### ${checkbox} ${priorityEmoji(task.priority)} ${task.title} ${statusEmoji(task.status)}`,
  ];

  if (task.description) {
    lines.push(`> ${task.description}`);
    lines.push("");
  }

  const meta = [];
  meta.push(`- **Priority:** ${task.priority.charAt(0).toUpperCase() + task.priority.slice(1)}`);
  meta.push(`- **Status:** ${task.status}`);
  meta.push(`- **Deadline:** ${formatDateHuman(task.deadline)}`);

  if (task.estimatedHours) {
    meta.push(`- **Estimated Time:** ${task.estimatedHours} hour(s)`);
  }

  if (task.tags?.length) {
    meta.push(`- **Tags:** ${task.tags.map((t) => `\`${t}\``).join(", ")}`);
  }

  if (task.notes) {
    meta.push(`- **Notes:** ${task.notes}`);
  }

  if (task.completedAt) {
    meta.push(`- **Completed At:** ${new Date(task.completedAt).toLocaleString()}`);
  }

  lines.push(...meta);
  lines.push("");
  lines.push("---");
  lines.push("");

  return lines.join("\n");
}

// ─────────────────────────────────────────
// Build a section with a heading + tasks
// ─────────────────────────────────────────
function buildSection(heading, emoji, tasks) {
  if (!tasks.length) return "";

  const sorted = sortByDeadline(tasks);
  const blocks = sorted.map(buildTaskBlock).join("\n");

  return `## ${emoji} ${heading}\n\n${blocks}`;
}

// ─────────────────────────────────────────
// Main Reminders Generator
// ─────────────────────────────────────────
export function generateReminders(tasks, hackathonName, outputPath) {
  const now = new Date().toLocaleString("en-US", {
    dateStyle: "full",
    timeStyle: "short",
  });

  // Stats
  const total = tasks.length;
  const completed = filterByStatus(tasks, "completed").length;
  const pending = filterByStatus(tasks, "pending").length;
  const inProgress = filterByStatus(tasks, "in-progress").length;
  const skipped = filterByStatus(tasks, "skipped").length;
  const progressPct = total > 0 ? Math.round((completed / total) * 100) : 0;

  // Progress bar (20 chars wide)
  const filled = Math.round(progressPct / 5);
  const progressBar = `[${"█".repeat(filled)}${"░".repeat(20 - filled)}] ${progressPct}%`;

  // Header
  const header = [
    `# 📋 Hackathon Task Reminders`,
    `### 🏆 ${hackathonName}`,
    "",
    `> Generated: ${now}`,
    "",
    "## 📊 Progress Overview",
    "",
    `\`\`\``,
    progressBar,
    `Total      : ${total}`,
    `✅ Done    : ${completed}`,
    `🔄 Active  : ${inProgress}`,
    `⏳ Pending : ${pending}`,
    `⏭️  Skipped : ${skipped}`,
    `\`\`\``,
    "",
    "---",
    "",
  ].join("\n");

  // Sections
  const sections = [
    buildSection("In Progress", "🔄", filterByStatus(tasks, "in-progress")),
    buildSection("Pending Tasks", "⏳", filterByStatus(tasks, "pending")),
    buildSection("Completed Tasks", "✅", filterByStatus(tasks, "completed")),
    buildSection("Skipped Tasks", "⏭️", filterByStatus(tasks, "skipped")),
  ]
    .filter(Boolean)
    .join("\n");

  // Footer
  const footer = [
    "",
    "---",
    "",
    `*This file was auto-generated by the Hackathon Action Agent.*`,
    `*Re-run the agent to refresh task statuses and regenerate outputs.*`,
  ].join("\n");

  writeText(outputPath, header + sections + footer);
}
